/**
 * Computes the current display phrase for `#preset-name` with a calm steady-state window
 * when "IN" a preset (`holdRemaining > 0` or `progress < 0.14` / `progress >= 0.88`),
 * and a gradual 4-stage creative semantic drift across `progress` in `[0.14, 0.88)`.
 */
export function computeSemanticDriftTitle(fromName, toName, progress = 0, holdRemaining = 0) {
  const cleanFrom = String(fromName || 'Classic Quartz Prism');
  const cleanTo = String(toName || cleanFrom);
  if (!cleanTo || cleanFrom === cleanTo || holdRemaining > 0 || progress < 0.14) {
    return cleanFrom;
  }
  if (progress >= 0.88) {
    return cleanTo;
  }

  // Map progress in [0.14, 0.88) -> 4 discrete semantic drift stages (0, 1, 2, 3)
  const u = Math.max(0, Math.min(0.9999, (progress - 0.14) / (0.88 - 0.14)));
  const stage = Math.floor(u * 4);

  const forwardKey = `${cleanFrom}->${cleanTo}`;
  if (SEMANTIC_DRIFT_CHAINS[forwardKey]) {
    return SEMANTIC_DRIFT_CHAINS[forwardKey][stage];
  }
  const reverseKey = `${cleanTo}->${cleanFrom}`;
  if (SEMANTIC_DRIFT_CHAINS[reverseKey]) {
    return SEMANTIC_DRIFT_CHAINS[reverseKey][3 - stage];
  }

  // Compositional fallback for arbitrary preset jumps or Randomized crystals
  const dnaA = PRESET_SEMANTIC_DNA[cleanFrom] || {
    adj: ['Vitreous', 'Crystalline'],
    mineral: [cleanFrom.split(' ')[0] || 'Crystal'],
    form: [cleanFrom.split(' ').slice(-1)[0] || 'Prism'],
  };
  const dnaB = PRESET_SEMANTIC_DNA[cleanTo] || {
    adj: ['Prismatic', 'Luminous'],
    mineral: [cleanTo.startsWith('Random') ? 'Alchemical-Gem' : (cleanTo.split(' ')[0] || 'Crystal')],
    form: [cleanTo.startsWith('Random') ? 'Cluster' : (cleanTo.split(' ').slice(-1)[0] || 'Spire')],
  };

  if (stage === 0) {
    return `${dnaA.adj[0]} ${dnaA.mineral[0]} ${dnaA.form[1] || dnaA.form[0]}`;
  }
  if (stage === 1) {
    return `${dnaB.adj[1] || dnaB.adj[0]} ${dnaA.mineral[1] || dnaA.mineral[0]} ${dnaB.form[0]}`;
  }
  if (stage === 2) {
    return `${dnaA.adj[1] || dnaA.adj[0]} ${dnaB.mineral[1] || dnaB.mineral[0]} ${dnaA.form[0]}`;
  }
  return `${dnaB.adj[0]} ${dnaB.mineral[0]} ${dnaB.form[0]}`;
}

